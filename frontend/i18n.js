let currentLang = "no";

function detectLanguage() {
  const saved = localStorage.getItem("poptoosdm_lang");
  if (saved && translations[saved]) return saved;
  const langs = navigator.languages || [navigator.language || "no"];
  for (const l of langs) {
    const code = l.split("-")[0].toLowerCase();
    if (translations[code]) return code;
  }
  return "no";
}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key])
    || (translations["no"] && translations["no"][key])
    || key;
}

/**
 * Oversett en feil/advarsel fra serveren. Serveren sender {code, params, message}
 * (backend/core/errors.py); vises som t("srv_" + code) med {param} satt inn.
 * Vanlige strenger (eldre svar, unntakstekster) vises som de er.
 */
function translateError(err) {
  if (!err) return t("unknown_error");
  if (typeof err === "string") return err;
  if (err.code && translations.no && translations.no["srv_" + err.code]) {
    const params = err.params || {};
    let text = t("srv_" + err.code).replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
    if (params.extra > 0) text += " " + t("srv_more").replace("{n}", params.extra);
    return text;
  }
  return err.message || t("unknown_error");
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  document.documentElement.lang = currentLang;
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("lang-active", btn.dataset.lang === currentLang);
  });
  _updateThemeBtn();
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("poptoosdm_lang", lang);
  applyTranslations();
  // Last brukerliste på nytt om admin er innlogget (for å oppdatere knapper)
  if (typeof loadUserList === "function") {
    loadUserList();
  }
}

